// 复制语言包并输出
const SUPPORTED_LOCALES = ['zh_CN', 'zh_TW', 'en', 'ja', 'ko', 'de', 'fr', 'es', 'pt_BR', 'ru', 'vi', 'id'];

for (const loc of SUPPORTED_LOCALES) {
  const locDir = path.join(BASE_DIR, loc);
  if (!fs.existsSync(locDir)) {
    fs.mkdirSync(locDir, { recursive: true });
  }

  const srcData = LOCALES_DATA[loc] || LOCALES_DATA['en'];
  const formatted = {};
  for (const [key, msg] of Object.entries(srcData)) {
    formatted[key] = { message: msg };
  }

  const outFile = path.join(locDir, 'messages.json');
  fs.writeFileSync(outFile, JSON.stringify(formatted, null, 2) + '\n', 'utf8');
  console.log(`[locales] Generated ${outFile}`);
}

console.log('[locales] All 12 locale packs updated successfully.');
