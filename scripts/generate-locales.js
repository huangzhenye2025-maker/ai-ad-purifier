function formatChromeMessages(dict) {
  const out = {};
  for (const [k, v] of Object.entries(dict)) {
    // In Chrome extension i18n messages.json, a literal $ must be written as $$
    // otherwise $7 in $7.99 is parsed as undefined 7th placeholder and stripped out.
    const escaped = typeof v === 'string' ? v.replace(/\$([0-9])/g, '$$$$$1') : v;
    out[k] = { message: escaped };
  }
  return out;
}

for (const [locale, dict] of Object.entries(LOCALES_DATA)) {
  const dir = path.join(BASE_DIR, locale);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  const file = path.join(dir, 'messages.json');
  const chromeFormat = formatChromeMessages(dict);
  fs.writeFileSync(file, JSON.stringify(chromeFormat, null, 2), 'utf8');
  console.log(`[i18n] Generated ${locale}/messages.json (${Object.keys(dict).length} keys)`);
}

